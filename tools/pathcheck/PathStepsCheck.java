package frc.robot;

import com.pathplanner.lib.auto.AutoBuilder;
import com.pathplanner.lib.config.ModuleConfig;
import com.pathplanner.lib.config.PIDConstants;
import com.pathplanner.lib.config.RobotConfig;
import com.pathplanner.lib.controllers.PPHolonomicDriveController;
import com.pathplanner.lib.path.PathPlannerPath;
import com.pathplanner.lib.path.Waypoint;
import edu.wpi.first.hal.HAL;
import edu.wpi.first.math.geometry.Pose2d;
import edu.wpi.first.math.geometry.Translation2d;
import edu.wpi.first.math.geometry.Twist2d;
import edu.wpi.first.math.kinematics.ChassisSpeeds;
import edu.wpi.first.math.system.plant.DCMotor;
import edu.wpi.first.wpilibj.simulation.DriverStationSim;
import edu.wpi.first.wpilibj.simulation.SimHooks;
import edu.wpi.first.wpilibj2.command.Command;
import edu.wpi.first.wpilibj2.command.CommandScheduler;
import edu.wpi.first.wpilibj2.command.Commands;
import edu.wpi.first.wpilibj2.command.SubsystemBase;
import java.util.ArrayList;
import java.util.List;

/**
 * Runs PathSteps (generated by Robot Code Builder) with the real PathPlannerLib and command
 * scheduler in simulated time, and prints where along the path each action started and ended.
 * Usage: java frc.robot.PathStepsCheck (with src/main/deploy/pathplanner/paths/Check.path).
 */
public final class PathStepsCheck {
  static Pose2d pose = new Pose2d();
  static ChassisSpeeds speeds = new ChassisSpeeds();
  static double time = 0;
  static PathPlannerPath path;
  static final List<String> log = new ArrayList<>();
  static int failures = 0;

  static class Sub extends SubsystemBase {
    Sub(String name) {
      setName(name);
    }
  }

  /** Nearest position (waypoint-relative) on the original path to a point. */
  static double posOf(Translation2d p) {
    List<Waypoint> w = path.getWaypoints();
    double best = 0;
    double bestDist = Double.MAX_VALUE;
    for (int s = 0; s < w.size() - 1; s++) {
      for (int i = 0; i <= 400; i++) {
        double t = i / 400.0;
        double u = 1 - t;
        Translation2d a = w.get(s).anchor();
        Translation2d b = w.get(s).nextControl();
        Translation2d c = w.get(s + 1).prevControl();
        Translation2d d = w.get(s + 1).anchor();
        double x = u * u * u * a.getX() + 3 * u * u * t * b.getX() + 3 * u * t * t * c.getX() + t * t * t * d.getX();
        double y = u * u * u * a.getY() + 3 * u * u * t * b.getY() + 3 * u * t * t * c.getY() + t * t * t * d.getY();
        double dist = Math.hypot(x - p.getX(), y - p.getY());
        if (dist < bestDist) {
          bestDist = dist;
          best = s + t;
        }
      }
    }
    return best;
  }

  static Command record(String name, Sub sub) {
    return Commands.startEnd(
        () -> log.add(String.format("%s start t=%.2f pos=%.2f", name, time, posOf(pose.getTranslation()))),
        () -> log.add(String.format("%s end t=%.2f pos=%.2f", name, time, posOf(pose.getTranslation()))),
        sub).withName(name);
  }

  static void check(String what, boolean ok, String detail) {
    System.out.println((ok ? "ok    " : "FAIL  ") + what + "  (" + detail + ")");
    if (!ok) {
      failures++;
    }
  }

  static double find(String prefix, String field) {
    for (String line : log) {
      if (line.startsWith(prefix)) {
        for (String part : line.split(" ")) {
          if (part.startsWith(field + "=")) {
            return Double.parseDouble(part.substring(field.length() + 1));
          }
        }
      }
    }
    return Double.NaN;
  }

  public static void main(String[] args) throws Exception {
    HAL.initialize(500, 0);
    DriverStationSim.setDsAttached(true);
    DriverStationSim.setAutonomous(true);
    DriverStationSim.setEnabled(true);
    DriverStationSim.notifyNewData();
    SimHooks.pauseTiming();

    Sub drive = new Sub("Drive");
    Sub intake = new Sub("Intake");
    Sub arm = new Sub("Arm");
    Sub lights = new Sub("Lights");
    intake.setDefaultCommand(intake.run(() -> {}).withName("Intake default"));
    ModuleConfig module = new ModuleConfig(0.048, 4.4, 1.2, DCMotor.getKrakenX60(1).withReduction(6.75), 60, 1);
    RobotConfig config = new RobotConfig(55, 6, module,
        new Translation2d(0.28, 0.28), new Translation2d(0.28, -0.28), new Translation2d(-0.28, 0.28), new Translation2d(-0.28, -0.28));
    AutoBuilder.configure(() -> pose, (p) -> pose = p, () -> speeds, (s, ff) -> speeds = s,
        new PPHolonomicDriveController(new PIDConstants(5, 0, 0), new PIDConstants(5, 0, 0)), config, () -> false, drive);

    // A path drawn and edited in Robot Code Builder (insert, mirror, append, reverse) must load and drive.
    PathPlannerPath edited = PathPlannerPath.fromPathFile("Edited");
    double editedTime = edited.generateTrajectory(new ChassisSpeeds(), edited.getIdealStartingState().rotation(), config).getTotalTimeSeconds();
    check("a path edited in the app loads in PathPlannerLib", edited.getWaypoints().size() == 5 && edited.getRotationTargets().size() == 1,
        edited.getWaypoints().size() + " waypoints, " + edited.getRotationTargets().size() + " rotation target");
    check("and PathPlanner can plan a drive along it", Double.isFinite(editedTime) && editedTime > 1, String.format("%.2f s", editedTime));

    path = PathPlannerPath.fromPathFile("Check");
    pose = path.getStartingHolonomicPose().orElseThrow();
    System.out.println("   whole path: " + path.generateTrajectory(new ChassisSpeeds(), pose.getRotation(), config).getTotalTimeSeconds() + " s, "
        + path.getAllPathPoints().size() + " points, start " + pose);
    var dbg = path.generateTrajectory(new ChassisSpeeds(), pose.getRotation(), config);
    for (int i = 0; i < Math.min(4, dbg.getStates().size()); i++) {
      var st = dbg.getState(i);
      System.out.println("   state " + i + ": t=" + st.timeSeconds + " v=" + st.linearVelocity + " pose=" + st.pose);
    }
    System.out.println("   states: " + dbg.getStates().size() + " last t=" + dbg.getEndState().timeSeconds + " module max " + config.moduleConfig.maxDriveVelocityMPS + " max force " + config.moduleConfig.wheelCOF);
    var pieceMethod = PathSteps.class.getDeclaredMethod("piece", PathPlannerPath.class, double.class, double.class, List.class, boolean.class);
    pieceMethod.setAccessible(true);
    for (double[] ft : new double[][] {{0, 1}, {1, 2}, {0.25, 1.75}, {0, 2}}) {
      PathPlannerPath piece = (PathPlannerPath) pieceMethod.invoke(null, path, ft[0], ft[1], List.of(), ft[1] < 2);
      var traj = piece.generateTrajectory(new ChassisSpeeds(), pose.getRotation(), config);
      Translation2d a = piece.getWaypoints().get(0).anchor();
      Translation2d b = piece.getWaypoints().get(piece.getWaypoints().size() - 1).anchor();
      System.out.printf("   piece %.2f-%.2f: %d waypoints, %d points, %.2f s, from (%.2f, %.2f) at %.3f to (%.2f, %.2f) at %.3f%n",
          ft[0], ft[1], piece.getWaypoints().size(), piece.getAllPathPoints().size(), traj.getTotalTimeSeconds(),
          a.getX(), a.getY(), posOf(a), b.getX(), b.getY(), posOf(b));
    }
    Command auto = PathSteps.follow(path,
        PathSteps.whileDriving(0.3, 0.9, "Intake zone", record("Intake zone", intake)),
        PathSteps.stopAt(1.0, "Arm stop", record("Arm stop", arm).withTimeout(0.6).asProxy()),
        PathSteps.startAt(0.5, "Lights", record("Lights", lights).withTimeout(4.0)),
        PathSteps.whileDriving(1.2, -1, "Intake to end", record("Intake to end", intake)));
    check("the path command needs only the drive", auto.getRequirements().size() == 1 && auto.getRequirements().contains(drive),
        auto.getRequirements().toString());
    CommandScheduler.getInstance().schedule(auto);

    double stoppedAtStop = 0;
    double stopPos = Double.NaN;
    boolean intakeDefaultDuringZone = false;
    double dt = 0.02;
    for (int i = 0; i < 1500; i++) {
      pose = pose.exp(new Twist2d(speeds.vxMetersPerSecond * dt, speeds.vyMetersPerSecond * dt, speeds.omegaRadiansPerSecond * dt));
      DriverStationSim.notifyNewData();
      CommandScheduler.getInstance().run();
      SimHooks.stepTiming(dt);
      time += dt;
      double speed = Math.hypot(speeds.vxMetersPerSecond, speeds.vyMetersPerSecond);
      double pos = posOf(pose.getTranslation());
      if (speed < 0.05 && pos > 0.8 && pos < 1.2 && time > 0.5) {
        stoppedAtStop += dt;
        stopPos = pos;
      }
      Command cur = CommandScheduler.getInstance().requiring(intake);
      if (cur != null && cur.getName().equals("Intake default") && pos > 0.45 && pos < 0.75) {
        intakeDefaultDuringZone = true;
      }
      if (!CommandScheduler.getInstance().isScheduled(auto) && time > 1) {
        break;
      }
    }
    // Let detached commands finish.
    for (int i = 0; i < 300; i++) {
      DriverStationSim.notifyNewData();
      CommandScheduler.getInstance().run();
      SimHooks.stepTiming(dt);
      time += dt;
    }
    log.forEach((l) -> System.out.println("   " + l));
    double endPos = posOf(pose.getTranslation());
    check("the robot finished at the end of the path", endPos > 1.97, String.format("pos %.2f", endPos));
    check("Intake zone starts near 0.3", Math.abs(find("Intake zone start", "pos") - 0.3) < 0.08, String.valueOf(find("Intake zone start", "pos")));
    check("Intake zone ends near 0.9", Math.abs(find("Intake zone end", "pos") - 0.9) < 0.08, String.valueOf(find("Intake zone end", "pos")));
    check("the intake's default command waits while the zone runs", !intakeDefaultDuringZone, "default seen in zone: " + intakeDefaultDuringZone);
    check("the robot stops at 1.0 for the stop action", Math.abs(stopPos - 1.0) < 0.03 && stoppedAtStop >= 0.55,
        String.format("stopped %.2f s at %.3f", stoppedAtStop, stopPos));
    double armStart = find("Arm stop start", "pos");
    check("the stop action runs at 1.0", Math.abs(armStart - 1.0) < 0.03, String.valueOf(armStart));
    double armSecs = find("Arm stop end", "t") - find("Arm stop start", "t");
    check("the stop action runs for its 0.6 s", Math.abs(armSecs - 0.6) < 0.05, String.format("%.2f s", armSecs));
    check("Lights start near 0.5", Math.abs(find("Lights start", "pos") - 0.5) < 0.08, String.valueOf(find("Lights start", "pos")));
    double lightSecs = find("Lights end", "t") - find("Lights start", "t");
    check("Lights keep going for 4 s, past the stop", Math.abs(lightSecs - 4.0) < 0.05, String.format("%.2f s", lightSecs));
    check("Intake to end starts near 1.2", Math.abs(find("Intake to end start", "pos") - 1.2) < 0.08, String.valueOf(find("Intake to end start", "pos")));
    check("Intake to end stops when the path ends", find("Intake to end end", "pos") > 1.97, String.valueOf(find("Intake to end end", "pos")));
    System.out.println(failures == 0 ? "All PathSteps checks passed" : failures + " PathSteps check(s) failed");
    System.exit(failures == 0 ? 0 : 1);
  }
}
